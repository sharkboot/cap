"""按 profile 生成 Dockerfile。

流程：
1. agent.build_agent_layer() 输出基础层（FROM + agent CLI 安装 + 薄壳 COPY）
2. 每个选中 capability.build() 输出能力层（npm install、COPY skills、ENV、VOLUME）
3. 合并所有 runtime_env() → 框架在 docker run 时注入（不落镜像）
4. 合并 post_start → 薄壳启动时执行
"""
from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path

from cap.agents import get_agent
from cap.capabilities import get_capability, _REGISTRY as CAP_REGISTRY
from cap.capabilities.base import CapabilityContext, CapabilityBuildOutput
from cap.profile import Profile


@dataclass
class DockerfileArtifact:
    dockerfile_text: str
    runtime_env: dict            # docker run 时 --env 注入
    runtime_volumes: list[str]   # docker run 时挂载
    post_start: list[str]        # 薄壳启动时执行
    health_probes: list[str]     # 健康检查端点（框架轮询）
    image_tag: str

    def write(self, out_dir: Path) -> Path:
        out_dir.mkdir(parents=True, exist_ok=True)
        path = out_dir / "Dockerfile"
        path.write_text(self.dockerfile_text, encoding="utf-8")
        return path


def render_dockerfile(
    profile: Profile,
    host_root: Path,
    image_tag: str | None = None,
    logger: logging.Logger | None = None,
) -> DockerfileArtifact:
    """生成一份完整的 Dockerfile + 运行时元数据。"""
    log = logger or logging.getLogger("cap.build")
    profile.validate_capabilities(CAP_REGISTRY)

    agent = get_agent(profile.agent)
    agent_ctx = _AgentCtxShim(profile=profile, logger=log)
    base_layer = agent.build_agent_layer(agent_ctx)

    # 逐个能力构建
    cap_outputs: list[tuple[str, CapabilityBuildOutput]] = []
    for ref in profile.capabilities:
        cap = get_capability(ref.name)
        ctx = CapabilityContext(
            profile=profile,
            host_root=host_root,
            params=ref.params or {},
            logger=log,
        )
        cap.pre_build_check(ctx)
        cap.validate(profile)
        out = cap.build(ctx)
        cap_outputs.append((ref.name, out))

    # 拼接 Dockerfile（注释只用 ASCII，避免构建器编码问题）
    lines: list[str] = []
    caps_str = ",".join(profile.capability_names())
    lines += [
        f"# generated by cap framework - capabilities=[{caps_str}]",
        "#",
    ]
    lines += base_layer
    for name, out in cap_outputs:
        lines.append(f"# --- capability: {name} ---")
        lines.extend(out.dockerfile_lines)
    lines.append("")

    # 合并 env / volumes / post_start / health
    merged_env: dict[str, str] = {}
    merged_vols: list[str] = []
    merged_post: list[str] = []
    probes: list[str] = []
    for name, out in cap_outputs:
        merged_env.update(out.env)
        merged_vols.extend(v for v in out.volumes if v not in merged_vols)
        merged_post.extend(out.post_start)
        if out.health_probe:
            probes.append(out.health_probe)
    if merged_env:
        lines += [
            "# --- image-layer env (non-secret) ---",
            *[f"ENV {k}={v}" for k, v in merged_env.items()],
            "",
        ]
    if merged_vols:
        vols_json = json.dumps(list(merged_vols))
        lines += [f"VOLUME {vols_json}", ""]

    # 运行时 env（敏感 / 宿主机决定）由各能力 runtime_env() 提供
    runtime_env: dict[str, str] = {}
    for ref in profile.capabilities:
        cap = get_capability(ref.name)
        ctx = CapabilityContext(
            profile=profile, host_root=host_root, params=ref.params or {}, logger=log
        )
        runtime_env.update(cap.runtime_env(ctx))

    lines += [
        "# --- CMD: start agent bridge ---",
        "CMD " + " ".join(f'"{c}"' if " " in c else c for c in agent.bridge_cmd(profile)),
    ]

    return DockerfileArtifact(
        dockerfile_text="\n".join(lines),
        runtime_env=runtime_env,
        runtime_volumes=merged_vols,
        post_start=merged_post,
        health_probes=probes,
        image_tag=image_tag or _default_tag(profile),
    )


class _AgentCtxShim:
    """给 AgentRuntime.build_agent_layer 的最小上下文（避免循环导入）。"""
    def __init__(self, profile, logger):
        self.profile = profile
        self.logger = logger


def _default_tag(profile: Profile) -> str:
    import hashlib
    h = hashlib.sha1(
        "|".join(profile.capability_names()).encode()
    ).hexdigest()[:10]
    return f"cap/{profile.agent}:{h}"
